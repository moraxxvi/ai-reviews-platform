"""Правила жалоб и отрицаний поверх ML-модели (гибридный подход).

Зачем: модель тональности обучена на отзывах целиком (метка по звёздам), где ~73% положительных.
Она плохо видит краткие жалобы внутри фразы («очень горячий») и не понимает отрицание («не греется»).
Правила задают тональность клаузы, если в ней есть явный признак жалобы или похвалы; иначе решает модель.

rule_sentiment(clause) -> 'negative' | 'positive' | None   (None = правил нет, решает модель)
"""
import re

# признаки жалобы (основы слов, ищем по подстроке в очищенной клаузе)
NEG_CUES = [
    "греет", "греют", "нагрев", "горяч", "перегрев", "жарит", "кипит",
    "тормоз", "лагает", "лаги", "зависа", "виснет", "глюч", "вылета",
    "разряжа", "садится", "быстро сел", "недолго держит", "не хватает",
    "дорого", "переплат", "хрип", "треск", "шумит", "скрип", "люфт",
    "ужас", "отстой", "разочар", "плох", "сломал", "не работает", "бракован", "задержа", "опоздал", "долго достав",
]
# признаки похвалы (для случая отрицания: «не держит заряд» = жалоба)
POS_CUES = ["держит", "хватает", "работает", "радует", "нравится", "быстр", "отличн", "супер", "шикарн", "рекомендую"]
# смягчающие слова: «нагрев минимальный», «шум незаметен» - это похвала, а не жалоба
MITIGATORS = ["минимальн", "небольш", "незаметн", "умеренн", "нормальн", "холодн", "прохладн", "отсутств", "в норме"]
NEGATORS = ("не", "нет", "ни", "без", "никогда", "вообще не")
_TOKEN = re.compile(r"[а-яa-z0-9]+")


def _has_neg_before(tokens, idx, window=3):
    return any(t in ("не", "нет", "ни", "без", "никогда") for t in tokens[max(0, idx - window):idx])


def _positions(clause, cues):
    """Позиции (номер слова) слов, содержащих любую из основ."""
    tokens = _TOKEN.findall(clause)
    out = []
    for i, tok in enumerate(tokens):
        if any(c in tok for c in cues if " " not in c):
            out.append(i)
    # многословные признаки
    for c in cues:
        if " " in c and c in clause:
            out.append(len(tokens) // 2)
    return tokens, out


def rule_sentiment(clause):
    clause = clause.lower()
    tokens, neg_pos = _positions(clause, NEG_CUES)
    if neg_pos:
        if any(m in clause for m in MITIGATORS):
            return "positive"
        # жалоба, если хотя бы один признак БЕЗ отрицания перед ним; иначе («не греется») - похвала
        if any(not _has_neg_before(tokens, i) for i in neg_pos):
            # «не работает» уже содержит отрицание в самой основе
            return "negative"
        return "positive"
    tokens, pos_pos = _positions(clause, POS_CUES)
    if pos_pos and all(_has_neg_before(tokens, i) for i in pos_pos):
        return "negative"  # «не держит заряд», «не радует»
    return None
