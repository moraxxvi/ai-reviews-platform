def match_aspects(clean_text):
    """Аспекты, упомянутые в уже очищенном тексте (словарь основ + список исключений)."""
    t = " " + clean_text + " "
    found = []
    for a, stems in ASPECTS.items():
        tt = t
        for bad in ASPECT_EXCLUDE.get(a, []):
            tt = tt.replace(bad, " ")
        if any(st in tt for st in stems):
            found.append(a)
    return found
