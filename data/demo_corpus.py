def gen_sentiment_clauses(n=3000, seed=7):
    """Клаузы с метками: positive / negative / neutral. Возвращает (список текстов, список меток)."""
    rnd = random.Random(seed)
    X, y = [], []
    for _ in range(n):
        r = rnd.random()
        if r < 0.42:
            asp = rnd.choice(list(POS))
            X.append(rnd.choice(POS[asp])); y.append("positive")
        elif r < 0.84:
            asp = rnd.choice(list(NEG))
            X.append(rnd.choice(NEG[asp])); y.append("negative")
        else:
            X.append(rnd.choice(NEUTRAL)); y.append("neutral")
    return X, y


def gen_intents(n_per_class=120, seed=11):
    rnd = random.Random(seed)
    X, y = [], []
    for intent, tpls in INTENT_TEMPLATES.items():
        for _ in range(n_per_class):
            t = rnd.choice(tpls)
            p, p2 = rnd.sample(_PRODUCTS, 2)
            text = t.format(cat=rnd.choice(_CATS), b=rnd.choice(_BUDGETS), asp_g=rnd.choice(_ASP), asp_n=rnd.choice(["камера", "батарея", "экран"]),
                            p=p, p2=p2, asp_q=rnd.choice(_ASP_Q))
            X.append(text); y.append(intent)
    return X, y


